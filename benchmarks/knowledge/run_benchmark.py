def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--godot", required=True, help="Godot 4.7.1 executable")
    parser.add_argument("--project", default=".", help="Project root under test")
    parser.add_argument("--profile", choices=sorted(PROFILES), default="ci")
    parser.add_argument("--report", default="knowledge-benchmark-report.json")
    parser.add_argument("--git-sha", default=os.getenv("GITHUB_SHA", ""))
    parser.add_argument("--fail-on-hard-gate", action="store_true")
    parser.add_argument("--formats", default="", help="Optional comma-separated format override")
    parser.add_argument("--timeout", type=int, default=0, help="Per-phase timeout override")
    return parser.parse_args()


def _linux_rss(pid: int) -> int:
    try:
        with open(f"/proc/{pid}/status", "r", encoding="utf-8") as handle:
            for line in handle:
                if line.startswith("VmRSS:"):
                    return int(line.split()[1]) * 1024
    except (FileNotFoundError, ProcessLookupError, PermissionError, ValueError):
        pass
    return 0


def _windows_rss(pid: int) -> int:
    if os.name != "nt":
        return 0

    class PROCESS_MEMORY_COUNTERS_EX(ctypes.Structure):
        _fields_ = [
            ("cb", ctypes.c_ulong),
            ("PageFaultCount", ctypes.c_ulong),
            ("PeakWorkingSetSize", ctypes.c_size_t),
            ("WorkingSetSize", ctypes.c_size_t),
            ("QuotaPeakPagedPoolUsage", ctypes.c_size_t),
            ("QuotaPagedPoolUsage", ctypes.c_size_t),
            ("QuotaPeakNonPagedPoolUsage", ctypes.c_size_t),
            ("QuotaNonPagedPoolUsage", ctypes.c_size_t),
            ("PagefileUsage", ctypes.c_size_t),
            ("PeakPagefileUsage", ctypes.c_size_t),
            ("PrivateUsage", ctypes.c_size_t),
        ]

    PROCESS_QUERY_LIMITED_INFORMATION = 0x1000
    PROCESS_VM_READ = 0x0010
    kernel32 = ctypes.windll.kernel32
    psapi = ctypes.windll.psapi
    handle = kernel32.OpenProcess(PROCESS_QUERY_LIMITED_INFORMATION | PROCESS_VM_READ, False, pid)
    if not handle:
        return 0
    try:
        counters = PROCESS_MEMORY_COUNTERS_EX()
        counters.cb = ctypes.sizeof(counters)
        if psapi.GetProcessMemoryInfo(handle, ctypes.byref(counters), counters.cb):
            return int(counters.WorkingSetSize)
    finally:
        kernel32.CloseHandle(handle)
    return 0


def process_rss(pid: int) -> int:
    if sys.platform.startswith("linux"):
        return _linux_rss(pid)
    if os.name == "nt":
        return _windows_rss(pid)
    return 0


def isolated_env(root: pathlib.Path) -> dict[str, str]:
    env = os.environ.copy()
    env["AURORA_KNOWLEDGE_BENCHMARK"] = "1"
    env["XDG_DATA_HOME"] = str(root / "xdg_data")
    env["XDG_CONFIG_HOME"] = str(root / "xdg_config")
    env["HOME"] = str(root / "home")
    env["APPDATA"] = str(root / "appdata")
    env["LOCALAPPDATA"] = str(root / "localappdata")
    for key in ("XDG_DATA_HOME", "XDG_CONFIG_HOME", "HOME", "APPDATA", "LOCALAPPDATA"):
        pathlib.Path(env[key]).mkdir(parents=True, exist_ok=True)
    # Do not inherit accidental provider credentials into the benchmark process.
    for key in list(env):
        upper = key.upper()
        if any(token in upper for token in ("OPENAI", "ANTHROPIC", "GEMINI", "OLLAMA", "AZURE_OPENAI")):
            env.pop(key, None)
    return env


def worker_path(project: pathlib.Path) -> pathlib.Path:
    return project / "benchmarks" / "knowledge" / "knowledge_benchmark_worker.gd"


def run_phase(
    godot: str,
    project: pathlib.Path,
    env: dict[str, str],
    phase: str,
    timeout_sec: int,
    **kwargs: Any,
) -> dict[str, Any]:
    command = [
        godot,
        "--headless",
        "--path",
        str(project),
        "--script",
        str(worker_path(project)),
        "--",
        "--phase",
        phase,
    ]
    for key, value in kwargs.items():
        command.extend([f"--{key}", str(value)])

    started = time.perf_counter()
    peak_rss = 0
    with tempfile.TemporaryFile(mode="w+t", encoding="utf-8") as output:
        process = subprocess.Popen(
            command,
            cwd=project,
            env=env,
            stdout=output,
            stderr=subprocess.STDOUT,
            text=True,
        )
        timed_out = False
        while process.poll() is None:
            peak_rss = max(peak_rss, process_rss(process.pid))
            if time.perf_counter() - started > timeout_sec:
                timed_out = True
                process.kill()
                break
            time.sleep(0.02)
        try:
            return_code = process.wait(timeout=10)
        except subprocess.TimeoutExpired:
            process.kill()
            return_code = process.wait()
        peak_rss = max(peak_rss, process_rss(process.pid))
        output.seek(0)
        stdout = output.read()

    wall_ms = (time.perf_counter() - started) * 1000.0
    parsed: dict[str, Any] | None = None
    for line in stdout.splitlines():
        if line.startswith(RESULT_PREFIX):
            try:
                value = json.loads(line[len(RESULT_PREFIX) :])
                if isinstance(value, dict):
                    parsed = value
            except json.JSONDecodeError:
                pass

    if parsed is None:
        parsed = {
            "ok": False,
            "harness_error": True,
            "error": "worker result missing",
            "stdout_tail": stdout[-4000:],
        }
    parsed["process_peak_rss_bytes"] = peak_rss
    parsed["process_wall_ms"] = wall_ms
    parsed["return_code"] = return_code
    parsed["timed_out"] = timed_out
    if timed_out or return_code != 0:
        parsed["ok"] = False
        parsed["harness_error"] = True
    return parsed


def godot_version(godot: str) -> str:
    try:
        proc = subprocess.run([godot, "--version"], check=False, capture_output=True, text=True, timeout=30)
        return (proc.stdout or proc.stderr).strip()
    except (OSError, subprocess.TimeoutExpired):
        return "unknown"


def git_sha(project: pathlib.Path, explicit: str) -> str:
    if explicit:
        return explicit
    try:
        proc = subprocess.run(
            ["git", "rev-parse", "HEAD"], cwd=project, check=False, capture_output=True, text=True, timeout=15
        )
        return proc.stdout.strip()
    except (OSError, subprocess.TimeoutExpired):
        return ""


def machine_identity(godot: str) -> dict[str, Any]:
    return {
        "platform": platform.system(),
        "platform_release": platform.release(),
        "machine": platform.machine(),
        "processor": platform.processor(),
        "python": platform.python_version(),
        "godot": godot_version(godot),
        "cpu_count": os.cpu_count(),
        "github_runner_name": os.getenv("RUNNER_NAME", ""),
        "github_runner_os": os.getenv("RUNNER_OS", ""),
        "github_runner_arch": os.getenv("RUNNER_ARCH", ""),
    }


def run_noop_peak(godot: str, project: pathlib.Path, timeout_sec: int) -> int:
    with tempfile.TemporaryDirectory(prefix="aurora-knowledge-noop-") as tmp:
        env = isolated_env(pathlib.Path(tmp))
        result = run_phase(godot, project, env, "noop", timeout_sec)
        return int(result.get("process_peak_rss_bytes", 0))


def peak_delta(result: dict[str, Any], baseline_rss: int) -> int:
    return max(0, int(result.get("process_peak_rss_bytes", 0)) - baseline_rss)


def run_knowledge_case(
    godot: str,
    project: pathlib.Path,
    baseline_rss: int,
    timeout_sec: int,
    format_name: str,
    size_mb: float,
    payload_bytes: int,
) -> dict[str, Any]:
    with tempfile.TemporaryDirectory(prefix=f"aurora-knowledge-{format_name}-") as tmp:
        env = isolated_env(pathlib.Path(tmp))
        imported = run_phase(
            godot,
            project,
            env,
            "knowledge_import",
            timeout_sec,
            format=format_name,
            size_mb=size_mb,
            payload_bytes=payload_bytes,
        )
        restarted = run_phase(
            godot,
            project,
            env,
            "knowledge_restart",
            timeout_sec,
            format=format_name,
            size_mb=size_mb,
        )
        removed = run_phase(
            godot,
            project,
            env,
            "knowledge_remove",
            timeout_sec,
            format=format_name,
            size_mb=size_mb,
        )
        dataset_bytes = int(imported.get("dataset_size_bytes", 0))
        delta = peak_delta(imported, baseline_rss)
        return {
            "kind": "knowledge_import",
            "format": format_name,
            "target_size_mb": size_mb,
            "import": imported,
            "restart": restarted,
            "removal": removed,
            "peak_rss_bytes": int(imported.get("process_peak_rss_bytes", 0)),
            "peak_rss_delta_bytes": delta,
            "memory_amplification_vs_dataset": (delta / dataset_bytes) if dataset_bytes > 0 else None,
            "storage_amplification_vs_dataset": (
                float(imported.get("store_size_bytes", 0)) / dataset_bytes if dataset_bytes > 0 else None
            ),
            "ok": bool(imported.get("ok", False)) and bool(restarted.get("ok", False)) and bool(removed.get("ok", False)),
        }


def run_source_scaling_case(
    godot: str,
    project: pathlib.Path,
    baseline_rss: int,
    timeout_sec: int,
    sources: int,
    records_per_source: int,
    payload_bytes: int,
) -> dict[str, Any]:
    with tempfile.TemporaryDirectory(prefix="aurora-source-scale-") as tmp:
        env = isolated_env(pathlib.Path(tmp))
        result = run_phase(
            godot,
            project,
            env,
            "source_scaling",
            timeout_sec,
            sources=sources,
            records_per_source=records_per_source,
            payload_bytes=payload_bytes,
        )
        result["peak_rss_delta_bytes"] = peak_delta(result, baseline_rss)
        return result


def run_memory_case(
    godot: str,
    project: pathlib.Path,
    baseline_rss: int,
    timeout_sec: int,
    records: int,
) -> dict[str, Any]:
    with tempfile.TemporaryDirectory(prefix="aurora-memory-scale-") as tmp:
        env = isolated_env(pathlib.Path(tmp))
        imported = run_phase(godot, project, env, "memory_import", timeout_sec, records=records)
        restarted = run_phase(godot, project, env, "memory_restart", timeout_sec, records=records)
        return {
            "kind": "memory",
            "record_count": records,
            "import": imported,
            "restart": restarted,
            "peak_rss_bytes": int(imported.get("process_peak_rss_bytes", 0)),
            "peak_rss_delta_bytes": peak_delta(imported, baseline_rss),
            "ok": bool(imported.get("ok", False)) and bool(restarted.get("ok", False)),
        }


def run_correctness_case(godot: str, project: pathlib.Path, baseline_rss: int, timeout_sec: int) -> dict[str, Any]:
    with tempfile.TemporaryDirectory(prefix="aurora-knowledge-correctness-") as tmp:
        env = isolated_env(pathlib.Path(tmp))
        result = run_phase(godot, project, env, "dedup_rollback", timeout_sec)
        result["peak_rss_delta_bytes"] = peak_delta(result, baseline_rss)
        return result


def ratio(new: float, old: float) -> float | None:
    if old <= 0:
        return None
    return new / old


def scaling_analysis(values: list[tuple[float, float]], label: str) -> dict[str, Any]:
    rows = sorted(values, key=lambda item: item[0])
    steps: list[dict[str, Any]] = []
    quadratic_suspected = False
    for previous, current in zip(rows, rows[1:]):
        n_ratio = ratio(float(current[0]), float(previous[0]))
        t_ratio = ratio(float(current[1]), float(previous[1]))
        normalized = None
        if n_ratio and t_ratio:
            normalized = t_ratio / n_ratio
            # User contract: doubling volume approaching 4x time is a blocker signal.
            if 1.8 <= n_ratio <= 2.2 and t_ratio >= 3.5:
                quadratic_suspected = True
        steps.append(
            {
                "from_n": previous[0],
                "to_n": current[0],
                "n_ratio": n_ratio,
                "time_ratio": t_ratio,
                "time_ratio_per_n_ratio": normalized,
            }
        )
    return {"metric": label, "steps": steps, "quadratic_suspected": quadratic_suspected}


def _case_time(case: dict[str, Any], section: str, field: str) -> float:
    return float(case.get(section, {}).get(field, 0.0))


def build_scaling(knowledge: list[dict[str, Any]], sources: list[dict[str, Any]], memory: list[dict[str, Any]]) -> dict[str, Any]:
    by_format: dict[str, list[tuple[float, float]]] = {}
    search_by_format: dict[str, list[tuple[float, float]]] = {}
    rss_by_format: dict[str, list[tuple[float, float]]] = {}
    for case in knowledge:
        fmt = str(case.get("format", ""))
        size = float(case.get("target_size_mb", 0))
        by_format.setdefault(fmt, []).append((size, _case_time(case, "import", "import_duration_ms")))
        search_by_format.setdefault(fmt, []).append(
            (size, float(case.get("import", {}).get("search", {}).get("p95_ms", 0.0)))
        )
        rss_by_format.setdefault(fmt, []).append((size, float(case.get("peak_rss_delta_bytes", 0))))

    source_values = [
        (float(case.get("source_count", 0)), float(case.get("import_duration_ms", 0.0))) for case in sources
    ]
    memory_values = [
        (float(case.get("record_count", 0)), _case_time(case, "import", "write_duration_ms")) for case in memory
    ]
    return {
        "knowledge_import": {fmt: scaling_analysis(values, f"{fmt}_import_ms") for fmt, values in by_format.items()},
        "knowledge_search_p95": {
            fmt: scaling_analysis(values, f"{fmt}_search_p95_ms") for fmt, values in search_by_format.items()
        },
        "knowledge_peak_rss_delta": {
            fmt: scaling_analysis(values, f"{fmt}_peak_rss_delta") for fmt, values in rss_by_format.items()
        },
        "source_count_import": scaling_analysis(source_values, "source_count_import_ms"),
        "memory_write": scaling_analysis(memory_values, "memory_write_ms"),
    }


def flatten_quadratic_flags(scaling: dict[str, Any]) -> list[str]:
    flags: list[str] = []
    for group_name, group in scaling.items():
        if isinstance(group, dict) and "quadratic_suspected" in group:
            if group.get("quadratic_suspected"):
                flags.append(group_name)
            continue
        if isinstance(group, dict):
            for name, result in group.items():
                if isinstance(result, dict) and result.get("quadratic_suspected"):
                    flags.append(f"{group_name}.{name}")
    return flags


def main() -> int:
    args = parse_args()
    project = pathlib.Path(args.project).resolve()
    godot = str(pathlib.Path(args.godot).resolve()) if pathlib.Path(args.godot).exists() else args.godot
    profile = dict(PROFILES[args.profile])
    formats = [item.strip().lower() for item in args.formats.split(",") if item.strip()] or list(profile["formats"])
    timeout_sec = args.timeout or int(profile["phase_timeout_sec"])

    if not worker_path(project).exists():
        raise SystemExit(f"benchmark worker not found: {worker_path(project)}")

    baseline_rss = run_noop_peak(godot, project, min(timeout_sec, 120))
    knowledge_cases: list[dict[str, Any]] = []
    for format_name in formats:
        for size_mb in profile["knowledge_mb"]:
            knowledge_cases.append(
                run_knowledge_case(
                    godot,
                    project,
                    baseline_rss,
                    timeout_sec,
                    format_name,
                    float(size_mb),
                    int(profile["payload_bytes"]),
                )
            )

    source_cases = [
        run_source_scaling_case(
            godot,
            project,
            baseline_rss,
            timeout_sec,
            int(count),
            int(profile["source_records"]),
            int(profile["payload_bytes"]),
        )
        for count in profile["source_counts"]
    ]
    memory_cases = [
        run_memory_case(godot, project, baseline_rss, timeout_sec, int(records))
        for records in profile["memory_records"]
    ]
    correctness = run_correctness_case(godot, project, baseline_rss, timeout_sec)

    scaling = build_scaling(knowledge_cases, source_cases, memory_cases)
    quadratic_flags = flatten_quadratic_flags(scaling)
    hard_failures: list[str] = []
    for case in knowledge_cases:
        if not case.get("ok"):
            hard_failures.append(f"knowledge:{case.get('format')}:{case.get('target_size_mb')}MiB")
    for case in source_cases:
        if not case.get("ok"):
            hard_failures.append(f"source-scaling:{case.get('source_count')}")
    for case in memory_cases:
        if not case.get("ok"):
            hard_failures.append(f"memory:{case.get('record_count')}")
    if not correctness.get("ok"):
        hard_failures.append("dedup-rollback-removal")

    semantic_self_reliance = True
    for case in memory_cases:
        status = case.get("import", {}).get("semantic_status", {})
        semantic_self_reliance = semantic_self_reliance and not bool(status.get("network_required", True))
        semantic_self_reliance = semantic_self_reliance and not bool(status.get("external_runtime_required", True))
        semantic_self_reliance = semantic_self_reliance and not bool(status.get("ollama_required", True))
    if not semantic_self_reliance:
        hard_failures.append("local-semantic-self-reliance")

    report: dict[str, Any] = {
        "schema_version": 1,
        "generated_at_utc": dt.datetime.now(dt.timezone.utc).isoformat(),
        "git_sha": git_sha(project, args.git_sha),
        "profile": args.profile,
        "machine": machine_identity(godot),
        "baseline_process_peak_rss_bytes": baseline_rss,
        "profile_contract": profile,
        "self_reliance": {
            "network_required": False,
            "external_runtime_required": False,
            "ollama_required": False,
            "remote_inference_used": False,
            "semantic_memory_verified_local": semantic_self_reliance,
        },
        "knowledge_cases": knowledge_cases,
        "source_scaling_cases": source_cases,
        "memory_cases": memory_cases,
        "correctness": correctness,
        "scaling": scaling,
        "performance_signals": {
            "quadratic_suspected": bool(quadratic_flags),
            "quadratic_metrics": quadratic_flags,
            "absolute_runner_time_is_not_a_gate": True,
        },
        "hard_gates": {
            "passed": not hard_failures,
            "failures": hard_failures,
            "no_crash_or_timeout": not any(
                bool(case.get("import", {}).get("timed_out")) for case in knowledge_cases
            ),
            "restart_search": all(bool(case.get("restart", {}).get("ok")) for case in knowledge_cases),
            "source_removal": all(bool(case.get("removal", {}).get("ok")) for case in knowledge_cases),
            "rollback": bool(correctness.get("rollback_ok", False)),
            "dedup_source_registry": bool(correctness.get("same_file_duplicate_suppressed", False))
            and bool(correctness.get("copy_alias_duplicate_suppressed", False)),
            "semantic_self_reliance": semantic_self_reliance,
        },
        "android_contract": {
            "physical_device_tested": False,
            "desktop_result_is_not_android_device_proof": True,
            "requirements": [
                "bounded_memory",
                "incremental_processing",
                "no_mandatory_external_service",
                "no_giant_temporary_copies",
                "private_storage",
                "failure_recovery",
                "cancellable_non_blocking_integration",
            ],
            "note": "This report is storage/runtime evidence for the named runner only; physical Android stress remains a separate device gate.",
        },
    }

    report_path = pathlib.Path(args.report)
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding="utf-8")

    print(json.dumps({
        "report": str(report_path),
        "hard_gates_passed": report["hard_gates"]["passed"],
        "hard_failures": hard_failures,
        "quadratic_metrics": quadratic_flags,
    }, ensure_ascii=False))
    if args.fail_on_hard_gate and hard_failures:
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
