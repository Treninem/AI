#!/usr/bin/env python3
"""AuroraFox Large Knowledge benchmark orchestrator.

Runs the real Godot Knowledge path in an isolated user-data environment, samples
resident memory without third-party packages, and emits one machine-readable
JSON report. Synthetic datasets are generated by the Godot runner and are never
stored in Git.
"""
from __future__ import annotations

import argparse
import ctypes
import json
import math
import os
from pathlib import Path
import platform
import queue
import shutil
import subprocess
import tempfile
import threading
import time
from typing import Any, Dict, Iterable, List, Optional, Tuple

REPORT_PREFIX = "AURORA_KNOWLEDGE_BENCHMARK_JSON="
MIB = 1024 * 1024


def _isolated_env(root: Path) -> Dict[str, str]:
    env = os.environ.copy()
    home = root / "home"
    home.mkdir(parents=True, exist_ok=True)
    env["HOME"] = str(home)
    if os.name == "nt":
        appdata = root / "appdata"
        local = root / "localappdata"
        appdata.mkdir(parents=True, exist_ok=True)
        local.mkdir(parents=True, exist_ok=True)
        env["APPDATA"] = str(appdata)
        env["LOCALAPPDATA"] = str(local)
        env["USERPROFILE"] = str(home)
    else:
        xdg = root / "xdg"
        xdg.mkdir(parents=True, exist_ok=True)
        env["XDG_DATA_HOME"] = str(xdg)
    # The benchmark contract is offline/self-reliant. Remove common proxy/API
    # knobs so an accidental external dependency is easier to detect.
    for name in (
        "OPENAI_API_KEY", "ANTHROPIC_API_KEY", "GEMINI_API_KEY",
        "GOOGLE_API_KEY", "HTTP_PROXY", "HTTPS_PROXY", "ALL_PROXY",
        "http_proxy", "https_proxy", "all_proxy",
    ):
        env.pop(name, None)
    env["AURORA_KNOWLEDGE_BENCHMARK_OFFLINE"] = "1"
    return env


def _linux_rss_bytes(pid: int) -> Optional[int]:
    try:
        text = Path(f"/proc/{pid}/status").read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return None
    for key in ("VmRSS:", "VmHWM:"):
        for line in text.splitlines():
            if line.startswith(key):
                parts = line.split()
                if len(parts) >= 2:
                    return int(parts[1]) * 1024
    return None


def _windows_rss_bytes(pid: int) -> Optional[int]:
    if os.name != "nt":
        return None

    class PROCESS_MEMORY_COUNTERS_EX(ctypes.Structure):
        _fields_ = [
            ("cb", ctypes.c_ulong),
            ("PageFaultCount", ctypes.c_ulong),
            ("PeakWorkingSetSize", ctypes.c_size_t),
            ("WorkingSetSize", ctypes.c_size_t),
            ("QuotaPeakPagedPoolUsage", ctypes.c_size_t),
            ("QuotaPagedPoolUsage", ctypes.c_size_t),
            ("QuotaPeakNonPagedPoolUsage", ctypes.c_size_t),
            ("QuotaNonPagedPoolUsage", ctypes.c_size_t),
            ("PagefileUsage", ctypes.c_size_t),
            ("PeakPagefileUsage", ctypes.c_size_t),
            ("PrivateUsage", ctypes.c_size_t),
        ]

    PROCESS_QUERY_INFORMATION = 0x0400
    PROCESS_VM_READ = 0x0010
    kernel32 = ctypes.windll.kernel32
    psapi = ctypes.windll.psapi
    handle = kernel32.OpenProcess(PROCESS_QUERY_INFORMATION | PROCESS_VM_READ, False, pid)
    if not handle:
        return None
    try:
        counters = PROCESS_MEMORY_COUNTERS_EX()
        counters.cb = ctypes.sizeof(counters)
        if not psapi.GetProcessMemoryInfo(handle, ctypes.byref(counters), counters.cb):
            return None
        return int(counters.WorkingSetSize)
    finally:
        kernel32.CloseHandle(handle)


def _rss_bytes(pid: int) -> Optional[int]:
    if sys_platform() == "linux":
        return _linux_rss_bytes(pid)
    if os.name == "nt":
        return _windows_rss_bytes(pid)
    return None


def sys_platform() -> str:
    return platform.system().lower()


def _sample_peak(proc: subprocess.Popen[str], stop: threading.Event, target: List[int]) -> None:
    peak = 0
    while not stop.is_set():
        value = _rss_bytes(proc.pid)
        if value is not None:
            peak = max(peak, value)
        if proc.poll() is not None:
            break
        time.sleep(0.05)
    value = _rss_bytes(proc.pid)
    if value is not None:
        peak = max(peak, value)
    target.append(peak)


def _parse_report(stdout: str) -> Dict[str, Any]:
    reports: List[Dict[str, Any]] = []
    for line in stdout.splitlines():
        if line.startswith(REPORT_PREFIX):
            payload = line[len(REPORT_PREFIX):]
            reports.append(json.loads(payload))
    if not reports:
        raise RuntimeError("Godot benchmark did not emit a machine-readable report")
    return reports[-1]


def _run_case(
    godot: Path,
    repo: Path,
    env: Dict[str, str],
    case_name: str,
    scenario: str,
    *,
    records: int = 0,
    payload_bytes: int = 0,
    fmt: str = "jsonl",
    source_name: str = "",
    timeout_s: int = 900,
    extra: Optional[Iterable[str]] = None,
) -> Dict[str, Any]:
    cmd = [
        str(godot), "--headless", "--path", str(repo),
        "--script", "benchmarks/knowledge/knowledge_benchmark.gd", "--",
        f"--scenario={scenario}",
        f"--records={records}",
        f"--payload-bytes={payload_bytes}",
        f"--format={fmt}",
        f"--case={case_name}",
    ]
    if source_name:
        cmd.append(f"--source-name={source_name}")
    if extra:
        cmd.extend(extra)

    started = time.perf_counter()
    proc = subprocess.Popen(
        cmd,
        cwd=repo,
        env=env,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    stop = threading.Event()
    samples: List[int] = []
    sampler = threading.Thread(target=_sample_peak, args=(proc, stop, samples), daemon=True)
    sampler.start()
    try:
        stdout, _ = proc.communicate(timeout=timeout_s)
    except subprocess.TimeoutExpired:
        proc.kill()
        stdout, _ = proc.communicate()
        raise RuntimeError(f"{case_name}: timeout after {timeout_s}s\n{stdout[-4000:]}")
    finally:
        stop.set()
        sampler.join(timeout=2)
    wall_ms = (time.perf_counter() - started) * 1000.0
    if proc.returncode != 0:
        raise RuntimeError(f"{case_name}: Godot exited {proc.returncode}\n{stdout[-8000:]}")
    report = _parse_report(stdout)
    report["case"] = case_name
    report["process_wall_ms"] = round(wall_ms, 3)
    report["peak_rss_bytes"] = max(samples) if samples else None
    report["stdout_tail"] = stdout.splitlines()[-8:]
    return report


def _size_records(target_mb: int, payload_bytes: int) -> int:
    # JSON metadata contributes a few hundred bytes per line. Deliberately
    # underestimate that overhead so generated datasets are at least the target.
    effective = max(256, payload_bytes + 220)
    return max(1, math.ceil(target_mb * MIB / effective))


def _ratio(current: float, previous: float) -> Optional[float]:
    if previous <= 0:
        return None
    return round(current / previous, 4)


def _scaling_summary(cases: List[Dict[str, Any]]) -> Dict[str, Any]:
    ordered = sorted(
        [c for c in cases if c.get("scenario") == "import_search" and c.get("format") == "jsonl" and c.get("scaling_point")],
        key=lambda c: int(c.get("record_count", 0)),
    )
    points: List[Dict[str, Any]] = []
    suspicious = 0
    previous: Optional[Dict[str, Any]] = None
    for case in ordered:
        point: Dict[str, Any] = {
            "records": int(case.get("record_count", 0)),
            "dataset_size_bytes": int(case.get("dataset_size_bytes", 0)),
            "import_duration_ms": float(case.get("import_duration_ms", 0.0)),
            "search_p95_ms": float(case.get("search", {}).get("p95_ms", 0.0)),
            "peak_rss_bytes": case.get("peak_rss_bytes"),
        }
        if previous is not None:
            import_ratio = _ratio(point["import_duration_ms"], float(previous.get("import_duration_ms", 0.0)))
            search_ratio = _ratio(point["search_p95_ms"], float(previous.get("search_p95_ms", 0.0)))
            point["vs_previous"] = {
                "records_ratio": _ratio(float(point["records"]), float(previous.get("records", 0))),
                "import_time_ratio": import_ratio,
                "search_p95_ratio": search_ratio,
            }
            # This is diagnostic rather than an absolute runner gate: repeated
            # ~4x growth while N doubles is a potential O(N^2) blocker.
            if import_ratio is not None and import_ratio >= 3.5:
                suspicious += 1
            if search_ratio is not None and search_ratio >= 3.5:
                suspicious += 1
        points.append(point)
        previous = point
    return {
        "points": points,
        "potential_quadratic_growth": suspicious >= 2,
        "suspicious_ratio_count": suspicious,
        "rule": "flag when doubling data repeatedly approaches/exceeds 3.5x time; do not use runner-specific absolute timings",
    }


def _self_reliance_ok(case: Dict[str, Any]) -> bool:
    status = case.get("self_reliance", {})
    return (
        status.get("network_required") is False
        and status.get("external_runtime_required") is False
        and status.get("ollama_required") is False
        and status.get("provider") == "aurorafox_local_vector"
    )


def _hard_correctness(cases: List[Dict[str, Any]]) -> Dict[str, Any]:
    failures: List[str] = []
    for case in cases:
        name = str(case.get("case", case.get("scenario", "unknown")))
        if not bool(case.get("ok", False)):
            failures.append(f"{name}: scenario returned ok=false")
        if case.get("errors"):
            failures.append(f"{name}: {case.get('errors')}")
        if not _self_reliance_ok(case):
            failures.append(f"{name}: local semantic self-reliance invariant failed")
    return {"ok": not failures, "failures": failures}


def run_profile(godot: Path, repo: Path, profile: str, include_500mb: bool) -> Dict[str, Any]:
    cases: List[Dict[str, Any]] = []
    errors: List[str] = []
    started = time.time()

    # PR smoke deliberately stays light; CI/stress exercise real large datasets.
    if profile == "smoke":
        scaling_records = [350, 700, 1400]
        scaling_payload = 768
        monolithic_records, monolithic_payload = 2200, 4096  # >8 MiB streaming threshold
        format_records, format_payload = 800, 768
    elif profile == "ci":
        scaling_records = [1800, 3600, 7200]
        scaling_payload = 2048
        monolithic_records, monolithic_payload = 3000, 4096
        format_records, format_payload = 4500, 2048  # ~10 MiB TXT/CSV class
    elif profile == "stress":
        scaling_records = [2500, 5000, 10000]
        scaling_payload = 4096
        monolithic_records, monolithic_payload = _size_records(50, 4096), 4096
        format_records, format_payload = _size_records(10, 4096), 4096
    else:
        raise ValueError(f"unknown profile: {profile}")

    def isolated_case(name: str, scenario: str, **kwargs: Any) -> None:
        with tempfile.TemporaryDirectory(prefix=f"aurora_kb_{name}_") as temp:
            env = _isolated_env(Path(temp))
            case = _run_case(godot, repo, env, name, scenario, **kwargs)
            cases.append(case)

    for records in scaling_records:
        name = f"jsonl_scale_{records}"
        isolated_case(
            name, "import_search", records=records, payload_bytes=scaling_payload,
            fmt="jsonl", extra=["--scaling-point=true"], timeout_s=1200,
        )

    # Formats with true streaming paths.
    isolated_case(
        "csv_stream", "import_search", records=format_records,
        payload_bytes=format_payload, fmt="csv", timeout_s=1200,
    )
    # For smoke, force TXT beyond 8 MiB so this still proves the large-text path.
    txt_records = format_records
    txt_payload = format_payload
    if txt_records * max(1, txt_payload) < 9 * MIB:
        txt_records = 2300
        txt_payload = 4096
    isolated_case(
        "txt_large_stream", "import_search", records=txt_records,
        payload_bytes=txt_payload, fmt="txt", timeout_s=1200,
    )
    isolated_case(
        "monolithic_json_stream", "monolithic_json",
        records=monolithic_records, payload_bytes=monolithic_payload,
        fmt="json", timeout_s=1800,
    )
    isolated_case(
        "dedup_source_removal", "dedup_removal",
        records=min(1200, max(300, format_records // 2)), payload_bytes=512,
        fmt="jsonl", timeout_s=900,
    )
    isolated_case(
        "rollback_partial_failure", "rollback",
        records=1, payload_bytes=9 * MIB, fmt="json", timeout_s=900,
    )

    # Restart proof requires two different Godot processes sharing the same
    # isolated user directory. That is intentionally stronger than reinstantiating
    # a Store object inside one process.
    with tempfile.TemporaryDirectory(prefix="aurora_kb_restart_") as temp:
        env = _isolated_env(Path(temp))
        prepare = _run_case(
            godot, repo, env, "restart_prepare", "restart_prepare",
            records=max(500, min(2000, format_records)), payload_bytes=1024,
            fmt="jsonl", source_name="restart_source.jsonl", timeout_s=900,
        )
        verify = _run_case(
            godot, repo, env, "restart_verify", "restart_verify",
            records=max(500, min(2000, format_records)), payload_bytes=1024,
            fmt="jsonl", source_name="restart_source.jsonl", timeout_s=900,
        )
        verify["restart_prepare_fingerprint"] = prepare.get("fingerprint_sha256", "")
        verify["restart_prepare_chunks"] = prepare.get("chunk_count", 0)
        cases.extend([prepare, verify])

    # Manual stress additionally covers requested 10/50/100/250 MiB synthetic
    # sources. 500 MiB is opt-in to avoid turning every manual stress run into a
    # giant runner job.
    if profile == "stress":
        sizes = [10, 50, 100, 250]
        if include_500mb:
            sizes.append(500)
        for target_mb in sizes:
            records = _size_records(target_mb, 4096)
            isolated_case(
                f"jsonl_target_{target_mb}mb", "import_search",
                records=records, payload_bytes=4096, fmt="jsonl",
                extra=[f"--target-mb={target_mb}"], timeout_s=max(1800, target_mb * 45),
            )

    correctness = _hard_correctness(cases)
    report: Dict[str, Any] = {
        "schema_version": 1,
        "benchmark": "aurorafox_large_knowledge_memory_performance",
        "generated_at_unix": int(time.time()),
        "profile": profile,
        "revision": os.environ.get("GITHUB_SHA", "unknown"),
        "platform": {
            "os": platform.system(),
            "release": platform.release(),
            "machine": platform.machine(),
            "python": platform.python_version(),
            "cpu_count": os.cpu_count(),
        },
        "dataset_contract": {
            "generated_deterministically": True,
            "large_fixtures_committed": False,
            "stress_target_mb": [10, 50, 100, 250] + ([500] if include_500mb else []),
        },
        "cases": cases,
        "scaling": _scaling_summary(cases),
        "hard_correctness": correctness,
        "android_contract": {
            "physical_android_device_tested": False,
            "desktop_results_are_not_android_device_proof": True,
            "requirements": [
                "bounded incremental processing",
                "no mandatory external AI or network",
                "no giant temporary source copies",
                "cancellation/failure recovery remains required",
                "private application storage remains required",
            ],
        },
        "errors": errors,
        "elapsed_seconds": round(time.time() - started, 3),
    }
    return report


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--godot", required=True, type=Path)
    parser.add_argument("--repo", type=Path, default=Path.cwd())
    parser.add_argument("--profile", choices=("smoke", "ci", "stress"), default="smoke")
    parser.add_argument("--output", type=Path, default=Path("knowledge-benchmark-report.json"))
    parser.add_argument("--include-500mb", action="store_true")
    args = parser.parse_args()

    godot = args.godot.expanduser().resolve()
    repo = args.repo.expanduser().resolve()
    if not godot.exists():
        raise SystemExit(f"Godot executable not found: {godot}")
    report = run_profile(godot, repo, args.profile, args.include_500mb)
    output = args.output if args.output.is_absolute() else repo / args.output
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({
        "report": str(output),
        "hard_correctness": report["hard_correctness"],
        "potential_quadratic_growth": report["scaling"]["potential_quadratic_growth"],
        "cases": len(report["cases"]),
    }, ensure_ascii=False))
    return 0 if report["hard_correctness"]["ok"] else 2


if __name__ == "__main__":
    raise SystemExit(main())
